// 将卦象数组转换为索引（二进制）
function hexagramToIndex(lines) {
  let index = 0;
  for (let i = 0; i < 6; i++) {
    if (lines[i] === 1) {
      index += Math.pow(2, i);
    }
  }
  return index;
}

